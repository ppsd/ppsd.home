export const planByKey = (key) => INSTALLMENT_PLANS.find((p) => p.key === key) || null

// เลือกแผนตามจำนวนชั้น + ราคา (ไม่ระบุชั้น = ถือเป็น 2 ชั้น ซึ่งเป็นแบบที่ใช้บ่อยสุด)
export function pickPlan(floors, value) {
  const f = Number(floors) || 2
  if (f <= 1) return planByKey('1f')
  if (f >= 3) return planByKey('3f')
  const v = Number(value) || 0
  if (v <= 3_000_000) return planByKey('2f-3m')
  if (v <= 10_000_000) return planByKey('2f-10m')
  return planByKey('2f-big')
}

// แตกเป็นงวดจริง — ปัดเศษเป็นบาท งวดสุดท้ายรับเศษให้ยอดรวมเท่าราคาพอดี
export function buildPlanRows(plan, total) {
  const t = Math.round(Number(total) || 0)
  let acc = 0
  return plan.rows.map(([pct, detail], i) => {
    const last = i === plan.rows.length - 1
    const amount = last ? t - acc : Math.round((t * pct) / 100)
    acc += amount
    return { no: i + 1, pct, detail, amount }
  })
}

