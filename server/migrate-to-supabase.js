// ย้ายข้อมูลจาก SQLite (server/data/ppsd.sqlite) ขึ้น Supabase (PostgreSQL) + ไฟล์แนบขึ้น Supabase Storage
// ---------------------------------------------------------------------------------------------
// วิธีใช้ (ที่เครื่องออฟฟิศ ดับเบิลคลิก migrate-supabase.bat หรือ):
//   node server/migrate-to-supabase.js            ย้ายทุกตาราง + ไฟล์แนบ (ลบตารางปลายทางชื่อเดียวกันแล้วสร้างใหม่ — รันซ้ำได้)
//   node server/migrate-to-supabase.js --dry-run  ดูแผน/จำนวนแถว ไม่เชื่อมต่อปลายทาง
//   node server/migrate-to-supabase.js --verify   เทียบจำนวนแถว SQLite ↔ Postgres อย่างเดียว
//   ตัวเลือก: --schema-only · --no-files · --files-only · --skip-existing (ข้ามไฟล์ที่อยู่บน Storage แล้ว) · --tables=houses,users · --db=<path.sqlite> · --bucket=<ชื่อ bucket>
// ตัวแปรระบบ: DATABASE_URL (Session pooler ของ Supabase) · SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY (สำหรับไฟล์แนบ)
// หมายเหตุ: เฟสนี้ "ก๊อปโครง 1:1" (ชนิดข้อมูลเดาจากข้อมูลจริง) ระบบยังใช้ SQLite ต่อจนกว่าจะสลับชั้น DB — รันกี่ครั้งก็ได้
import Database from 'better-sqlite3'
import pg from 'pg'
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const args = process.argv.slice(2)
const flag = (n) => args.includes('--' + n)
const opt = (n, d = '') => { const a = args.find((x) => x.startsWith('--' + n + '=')); return a ? a.slice(n.length + 3) : d }
const DRY = flag('dry-run'), VERIFY = flag('verify'), SCHEMA_ONLY = flag('schema-only'), NO_FILES = flag('no-files'), FILES_ONLY = flag('files-only'), SKIP_EXISTING = flag('skip-existing')
const ONLY = opt('tables') ? opt('tables').split(',').map((s) => s.trim()).filter(Boolean) : null
const DB_PATH = opt('db') || process.env.PPSD_DB || join(__dirname, 'data', 'ppsd.sqlite')
const FILES_DIR = join(__dirname, 'data', 'files')
const BUCKET = opt('bucket') || process.env.SUPABASE_BUCKET || 'ppsd-files'
const log = (...a) => console.log(...a)
const t0 = Date.now()

if (!existsSync(DB_PATH)) { console.error('ไม่พบไฟล์ฐานข้อมูล:', DB_PATH); process.exit(1) }
const sq = new Database(DB_PATH, { readonly: true, fileMustExist: true })
const q = (s) => '"' + String(s).replace(/"/g, '""') + '"' // quote identifier (กันชื่อคอลัมน์ชนคำสงวน เช่น by, order)

// ---------- 1) อ่านโครงจาก SQLite + เดาชนิดจากข้อมูลจริง ----------
function tablesOf() {
  return sq.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all().map((r) => r.name)
    .filter((t) => !ONLY || ONLY.includes(t))
}
function describe(table) {
  const cols = sq.prepare(`PRAGMA table_info(${q(table)})`).all()
  const rowCount = sq.prepare(`SELECT COUNT(*) c FROM ${q(table)}`).get().c
  const out = cols.map((c) => {
    const decl = String(c.type || '').toUpperCase()
    const isPk = c.pk === 1 && cols.filter((x) => x.pk).length === 1 && /INT/.test(decl)
    // ชนิดจริงที่พบในคอลัมน์ (SQLite เก็บแบบยืดหยุ่น — ข้อมูลเป็นตัวตัดสิน)
    const kinds = rowCount ? sq.prepare(`SELECT DISTINCT typeof(${q(c.name)}) k FROM ${q(table)}`).all().map((r) => r.k) : []
    const nonNull = kinds.filter((k) => k !== 'null')
    let pgType
    if (isPk) pgType = 'bigint'
    else if (nonNull.length === 0) pgType = /INT/.test(decl) ? 'bigint' : /REAL|FLOA|DOUB|NUM/.test(decl) ? 'double precision' : 'text'
    else if (nonNull.every((k) => k === 'integer')) pgType = /REAL|FLOA|DOUB/.test(decl) ? 'double precision' : 'bigint'
    else if (nonNull.every((k) => k === 'integer' || k === 'real')) pgType = 'double precision'
    else if (nonNull.every((k) => k === 'blob')) pgType = 'bytea'
    else pgType = 'text'
    // bigint ที่ค่าเกินช่วง → double
    if (pgType === 'bigint' && !isPk && rowCount) {
      const mx = sq.prepare(`SELECT MAX(ABS(${q(c.name)})) m FROM ${q(table)} WHERE typeof(${q(c.name)})='integer'`).get().m
      if (mx != null && Math.abs(Number(mx)) > 9.2e18) pgType = 'numeric'
    }
    return { name: c.name, decl, pgType, isPk, notnull: !!c.notnull && !isPk }
  })
  const uniques = sq.prepare(`PRAGMA index_list(${q(table)})`).all().filter((i) => i.unique && !/^sqlite_autoindex/.test(i.name) || (i.unique && i.origin === 'u'))
    .map((i) => ({ name: i.name, cols: sq.prepare(`PRAGMA index_info(${q(i.name)})`).all().map((x) => x.name) }))
  return { table, cols: out, rowCount, uniques }
}
function createSql(d) {
  const defs = d.cols.map((c) => c.isPk ? `${q(c.name)} bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY` : `${q(c.name)} ${c.pgType}`)
  const lines = [`DROP TABLE IF EXISTS ${q(d.table)} CASCADE;`, `CREATE TABLE ${q(d.table)} (\n  ${defs.join(',\n  ')}\n);`]
  d.uniques.forEach((u, i) => lines.push(`CREATE UNIQUE INDEX ${q(`${d.table}_u${i + 1}`)} ON ${q(d.table)} (${u.cols.map(q).join(', ')});`))
  return lines.join('\n')
}
const conv = (v, c) => {
  if (v == null) return null
  if (c.pgType === 'text') return typeof v === 'string' ? v.replace(/\u0000/g, '') : Buffer.isBuffer(v) ? v.toString('base64') : String(v)
  if (c.pgType === 'bigint') return typeof v === 'number' ? Math.trunc(v) : (Number.isFinite(Number(v)) ? Math.trunc(Number(v)) : null)
  if (c.pgType === 'double precision' || c.pgType === 'numeric') return Number.isFinite(Number(v)) ? Number(v) : null
  return v
}

// ---------- 2) เชื่อมต่อ Postgres ----------
function pgClient() {
  const url = process.env.DATABASE_URL
  if (!url) { console.error('ไม่พบ DATABASE_URL — ใส่ใน server/data/supabase.env (Session pooler ของ Supabase)'); process.exit(1) }
  const local = /localhost|127\.0\.0\.1/.test(url)
  return new pg.Client({ connectionString: url, ssl: local ? false : { rejectUnauthorized: false }, statement_timeout: 0 })
}

async function migrateTables(client, descs) {
  const report = []
  for (const d of descs) {
    const started = Date.now()
    await client.query('BEGIN')
    try {
      await client.query(createSql(d))
      let copied = 0
      if (!SCHEMA_ONLY && d.rowCount) {
        const cols = d.cols
        const chunk = Math.max(1, Math.min(500, Math.floor(60000 / cols.length)))
        const stmt = sq.prepare(`SELECT * FROM ${q(d.table)} ORDER BY rowid`)
        let batch = []
        const flush = async () => {
          if (!batch.length) return
          const params = []; const tuples = []
          for (const row of batch) {
            const ph = cols.map((c) => { params.push(conv(row[c.name], c)); return '$' + params.length })
            tuples.push('(' + ph.join(',') + ')')
          }
          await client.query(`INSERT INTO ${q(d.table)} (${cols.map((c) => q(c.name)).join(',')}) VALUES ${tuples.join(',')}`, params)
          copied += batch.length; batch = []
        }
        for (const row of stmt.iterate()) { batch.push(row); if (batch.length >= chunk) await flush() }
        await flush()
        const pk = cols.find((c) => c.isPk)
        if (pk) await client.query(`SELECT setval(pg_get_serial_sequence('${q(d.table)}', '${pk.name}'), COALESCE((SELECT MAX(${q(pk.name)}) FROM ${q(d.table)}), 1), (SELECT MAX(${q(pk.name)}) FROM ${q(d.table)}) IS NOT NULL)`)
      }
      await client.query('COMMIT')
      report.push({ table: d.table, rows: d.rowCount, copied, ms: Date.now() - started })
      log(`  ✓ ${d.table.padEnd(22)} ${String(copied).padStart(7)} / ${String(d.rowCount).padStart(7)} แถว  (${((Date.now() - started) / 1000).toFixed(1)}s)`)
    } catch (e) {
      await client.query('ROLLBACK').catch(() => {})
      log(`  ✗ ${d.table}: ${e.message}`)
      report.push({ table: d.table, rows: d.rowCount, copied: 0, error: e.message })
    }
  }
  return report
}

async function verifyTables(client, descs) {
  let bad = 0
  for (const d of descs) {
    let pgCount = null
    try { pgCount = Number((await client.query(`SELECT COUNT(*) c FROM ${q(d.table)}`)).rows[0].c) } catch { pgCount = null }
    const ok = pgCount === d.rowCount
    if (!ok) bad++
    log(`  ${ok ? '✓' : '✗'} ${d.table.padEnd(22)} SQLite ${String(d.rowCount).padStart(7)}  Postgres ${pgCount == null ? '(ไม่มีตาราง)' : String(pgCount).padStart(7)}`)
  }
  return bad
}

// ---------- 3) ไฟล์แนบ → Supabase Storage ----------
async function migrateFiles() {
  const base = (process.env.SUPABASE_URL || '').replace(/\/$/, '')
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY || ''
  if (!base || !key) { log('  - ข้ามไฟล์แนบ: ไม่มี SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY'); return { uploaded: 0, skipped: 0, failed: 0 } }
  if (!existsSync(FILES_DIR)) { log('  - ไม่มีโฟลเดอร์ไฟล์แนบ', FILES_DIR); return { uploaded: 0, skipped: 0, failed: 0 } }
  const H = { apikey: key, Authorization: 'Bearer ' + key }
  // ตรวจ key ก่อน: service_role ต้องเป็น JWT (ขึ้นต้น eyJ) ของโปรเจกต์เดียวกับ SUPABASE_URL และ role = service_role
  const ref = (base.match(/https?:\/\/([a-z0-9]+)\.supabase\.co/i) || [])[1] || ''
  if (key.startsWith('eyJ')) {
    try {
      const payload = JSON.parse(Buffer.from(key.split('.')[1].replace(/-/g, '+').replace(/_/g, '/'), 'base64').toString('utf8'))
      if (payload.role !== 'service_role') { log(`  ✗ key ที่ใส่เป็น role "${payload.role}" ไม่ใช่ service_role — ไปที่ Project Settings → API → ก๊อป "service_role" (secret)`); return { uploaded: 0, skipped: 0, failed: 1 } }
      if (ref && payload.ref && payload.ref !== ref) { log(`  ✗ key นี้เป็นของโปรเจกต์ ${payload.ref} แต่ SUPABASE_URL เป็นโปรเจกต์ ${ref} — ก๊อป key จากโปรเจกต์เดียวกัน`); return { uploaded: 0, skipped: 0, failed: 1 } }
    } catch { log('  ! อ่าน key ไม่ได้ (รูปแบบ JWT ผิด) — ลองก๊อปใหม่ทั้งบรรทัด ไม่มีช่องว่าง/ขึ้นบรรทัด') }
  } else if (!key.startsWith('sb_secret_')) log('  ! SUPABASE_SERVICE_ROLE_KEY ไม่ใช่รูปแบบที่รู้จัก (ควรขึ้นต้น eyJ หรือ sb_secret_)')
  // สร้าง bucket (private) ถ้ายังไม่มี
  const mk = await fetch(`${base}/storage/v1/bucket`, { method: 'POST', headers: { ...H, 'Content-Type': 'application/json' }, body: JSON.stringify({ id: BUCKET, name: BUCKET, public: false }) })
  if (!mk.ok && mk.status !== 409 && !(await mk.text()).includes('already exists')) log(`  ! สร้าง bucket ${BUCKET} ไม่ได้ (HTTP ${mk.status}) — จะลองอัปโหลดต่อ`)
  const meta = new Map(sq.prepare('SELECT id, name, mime, size FROM files').all().map((r) => [String(r.id), r]))
  const names = readdirSync(FILES_DIR).filter((f) => statSync(join(FILES_DIR, f)).isFile())
  let uploaded = 0, skipped = 0, failed = 0
  const tooBig = []
  const fmtMB = (n) => (n / 1048576).toFixed(1) + ' MB'
  for (const f of names) {
    const m = meta.get(f)
    const path = `files/${f}`
    const buf = readFileSync(join(FILES_DIR, f))
    if (SKIP_EXISTING && !DRY) { // ข้ามไฟล์ที่อยู่บน Storage แล้วและขนาดเท่ากัน (รันซ้ำเร็วขึ้น)
      try {
        const h = await fetch(`${base}/storage/v1/object/${BUCKET}/${path}`, { method: 'HEAD', headers: H })
        if (h.ok && Number(h.headers.get('content-length') || -1) === buf.length) { skipped++; continue }
      } catch { /* ลองอัปโหลดต่อ */ }
    }
    if (!DRY) {
      const r = await fetch(`${base}/storage/v1/object/${BUCKET}/${path}`, { method: 'POST', headers: { ...H, 'Content-Type': m?.mime || 'application/octet-stream', 'x-upsert': 'true' }, body: buf })
      if (r.ok) uploaded++
      else {
        failed++
        const body = (await r.text()).slice(0, 160)
        log(`  ✗ ${f} (${m?.name || '?'} · ${fmtMB(buf.length)}): HTTP ${r.status} ${body}`)
        if (/EntityTooLarge|Payload too large|413/.test(body)) tooBig.push({ f, name: m?.name || '', size: buf.length })
        if (/signature verification failed|Unauthorized|AccessDenied|invalid.*jwt/i.test(body) && uploaded === 0) {
          log('  ✗ หยุดอัปโหลด: key ไม่ผ่านการตรวจสอบ — ก๊อป service_role key ใหม่จาก Project Settings → API ของโปรเจกต์นี้ แล้วรัน migrate-supabase.bat --files-only')
          failed += names.length - (uploaded + failed + skipped)
          break
        }
      }
    } else skipped++
    if ((uploaded + failed + skipped) % 50 === 0) log(`  … ไฟล์ ${uploaded + failed + skipped}/${names.length}`)
  }
  log(`  ✓ ไฟล์แนบ: อัปโหลด ${uploaded} · ข้าม(มีแล้ว) ${skipped} · ล้มเหลว ${failed} · ทั้งหมด ${names.length} (bucket ${BUCKET})`)
  if (tooBig.length) {
    log(`  ! ${tooBig.length} ไฟล์ใหญ่เกินเพดานต่อไฟล์ของ Supabase Storage (ค่าเริ่มต้น 50 MB):`)
    tooBig.forEach((t) => log(`      - ไฟล์ #${t.f} ${t.name} ${fmtMB(t.size)}`))
    log('    แก้: Supabase → Project Settings → Storage → "Upload file size limit" ตั้งให้สูงกว่าไฟล์ที่ใหญ่สุด (แพ็กเกจ Pro ตั้งได้ถึง 50 GB · Free สูงสุด 50 MB) แล้วรัน migrate-supabase.bat --files-only --skip-existing')
  }
  return { uploaded, skipped, failed }
}

// ---------- main ----------
;(async () => {
  const descs = tablesOf().map(describe)
  const totalRows = descs.reduce((s, d) => s + d.rowCount, 0)
  log(`ฐานข้อมูลต้นทาง: ${DB_PATH}`)
  log(`ตาราง ${descs.length} · แถวรวม ${totalRows.toLocaleString()} · ไฟล์แนบ ${existsSync(FILES_DIR) ? readdirSync(FILES_DIR).length : 0}`)
  // บอกว่า "สด" แค่ไหน: รายการล่าสุดในตารางหลัก (ถ้าเก่ากว่าที่คาด = เปิดผิดไฟล์/ผิดโฟลเดอร์)
  try {
    // รายการที่ "เพิ่มล่าสุด" (ตาม id) — ไม่ใช้ MAX(วันที่) เพราะวันที่แบบไทย "9 ก.ย. 69" เรียงเป็นข้อความไม่ได้
    const last = (t, col) => { try { const r = sq.prepare(`SELECT ${q(col)} v FROM ${q(t)} ORDER BY rowid DESC LIMIT 1`).get(); return r?.v || '-' } catch { return '-' } }
    log(`รายการล่าสุดในต้นทาง: audit ${String(last('audit', 'ts')).slice(0, 19)} · PR ${last('purchase_requests', 'date')} · PO ${last('purchase_orders', 'date')} · ลงเวลา ${last('attendance', 'date')} · รายจ่าย ${last('expenses', 'date')}`)
    const st = statSync(DB_PATH); log(`ไฟล์ต้นทางแก้ไขล่าสุด: ${st.mtime.toLocaleString('th-TH')} · ขนาด ${(st.size / 1048576).toFixed(1)} MB${existsSync(DB_PATH + '-wal') ? ` · WAL ${(statSync(DB_PATH + '-wal').size / 1024).toFixed(0)} KB (รวมอยู่ในการอ่านแล้ว)` : ''}`)
  } catch { /* ignore */ }
  if (DRY) {
    if (existsSync(FILES_DIR)) {
      const big = readdirSync(FILES_DIR).map((f) => ({ f, size: statSync(join(FILES_DIR, f)).size })).filter((x) => x.size > 50 * 1048576)
      if (big.length) log(`\n[dry-run] ไฟล์แนบที่ใหญ่เกิน 50 MB (ต้องเพิ่มเพดานใน Supabase → Settings → Storage ก่อน): ${big.map((x) => `#${x.f} ${(x.size / 1048576).toFixed(1)} MB`).join(', ')}`)
    }
    log('\n[dry-run] แผนโครงตาราง Postgres:')
    for (const d of descs) log(`\n-- ${d.table} (${d.rowCount} แถว)\n${createSql(d)}`)
    log('\n[dry-run] ไม่ได้เชื่อมต่อปลายทาง ไม่มีอะไรถูกเขียน')
    return
  }
  if (FILES_ONLY) { // เฉพาะไฟล์แนบ ไม่ต้องต่อฐานข้อมูล
    log('\nไฟล์แนบ → Supabase Storage:'); const fr = await migrateFiles(); if (fr.failed) process.exitCode = 2
    sq.close(); log(`\nใช้เวลา ${((Date.now() - t0) / 1000).toFixed(1)} วินาที`); return
  }
  const client = pgClient()
  await client.connect()
  const ver = (await client.query('SELECT version()')).rows[0].version
  log(`ปลายทาง: ${ver.split(',')[0]}`)
  try {
    if (VERIFY) {
      log('\nเทียบจำนวนแถว:')
      const bad = await verifyTables(client, descs)
      log(bad ? `\n✗ ไม่ตรง ${bad} ตาราง` : '\n✓ ตรงกันทุกตาราง')
      process.exitCode = bad ? 2 : 0
      return
    }
    let report = []
    if (!FILES_ONLY) {
      log(`\nย้ายตาราง (${SCHEMA_ONLY ? 'เฉพาะโครง' : 'โครง + ข้อมูล'}):`)
      report = await migrateTables(client, descs)
      const errs = report.filter((r) => r.error)
      log(`\nสรุป: สำเร็จ ${report.length - errs.length}/${report.length} ตาราง · ${report.reduce((s, r) => s + (r.copied || 0), 0).toLocaleString()} แถว`)
      if (errs.length) { log('ตารางที่ล้มเหลว:'); errs.forEach((r) => log(`  - ${r.table}: ${r.error}`)); process.exitCode = 2 }
      if (!SCHEMA_ONLY) { log('\nตรวจสอบจำนวนแถว:'); const bad = await verifyTables(client, descs); if (bad) process.exitCode = 2 }
    }
    if (!NO_FILES && !SCHEMA_ONLY) { log('\nไฟล์แนบ → Supabase Storage:'); const fr = await migrateFiles(); if (fr.failed) process.exitCode = 2 }
  } finally {
    await client.end().catch(() => {})
    sq.close()
    log(`\nใช้เวลา ${((Date.now() - t0) / 1000).toFixed(1)} วินาที`)
  }
})().catch((e) => {
  console.error('ล้มเหลว:', e.message)
  const m = String(e.message || '')
  if (/tenant|not found/i.test(m) && /postgres\./.test(m)) console.error('→ โฮสต์ pooler ใน DATABASE_URL ไม่ตรงกับ region ของโปรเจกต์ (เช่นใช้ aws-0-ap-southeast-1 แต่โปรเจกต์อยู่ ap-northeast-1) — ก๊อป connection string ทั้งบรรทัดจาก Supabase → Connect → Session pooler มาวางแทน อย่าแก้มือ')
  else if (/password authentication failed/i.test(m)) console.error('→ รหัสผ่าน DB ไม่ถูกต้อง — ตั้งใหม่ได้ที่ Project Settings → Database → Reset database password แล้วใส่แทน [YOUR-PASSWORD]')
  else if (/ENOTFOUND|EAI_AGAIN/i.test(m)) console.error('→ หาโฮสต์ไม่เจอ — เช็คอินเทอร์เน็ต และโฮสต์ใน DATABASE_URL')
  else if (/ECONNREFUSED|ETIMEDOUT/i.test(m)) console.error('→ ต่อไม่ถึงพอร์ต 5432 — เครือข่ายออฟฟิศอาจบล็อก ลองใช้ Transaction pooler พอร์ต 6543 หรือเน็ตอื่น')
  process.exit(1)
})
