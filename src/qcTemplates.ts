// ---------- helpers ----------
export const qcPhaseName = (id: string) => QC_PHASES.find((p) => p.id === id)?.name || ''
export const qcFormsOfPhase = (phase: string) => QC_FORMS.filter((f) => f.phases.includes(phase))
export const qcCategoriesOfPhase = (phase: string) => Array.from(new Set(qcFormsOfPhase(phase).map((f) => f.category)))
export const qcFormsOf = (phase: string, category: string) => qcFormsOfPhase(phase).filter((f) => f.category === category)
export const qcFormById = (id: string) => QC_FORMS.find((f) => f.id === id)
export const qcFormItems = (f: QcForm) => f.sections.flatMap((s) => s.items.map((text) => ({ section: s.name, text })))
export const qcFormCount = (f: QcForm) => f.sections.reduce((n, s) => n + s.items.length, 0)
// ป้ายปุ่มผลตรวจตามชนิดฟอร์ม — ใบเก่า (ก่อนเปลี่ยนชุดฟอร์ม) ใช้ อนุมัติ/แก้ไข
export const qcLabels = (kind?: string): [string, string] => kind === 'มี/ไม่มี' ? ['มี', 'ไม่มี'] : kind === 'ผ่าน/ไม่ผ่าน' ? ['ผ่าน', 'ไม่ผ่าน'] : ['อนุมัติ', 'แก้ไข']
export const qcIsPass = (r: string) => r === 'ผ่าน' || r === 'มี' || r === 'อนุมัติ'
export const qcIsFail = (r: string) => r === 'ไม่ผ่าน' || r === 'ไม่มี' || r === 'แก้ไข'
// สถานะใบตรวจจากผลรายข้อ
export const qcDeriveStatus = (items: { result: string }[]) => {
  if (items.some((i) => qcIsFail(i.result))) return 'ต้องแก้ไข'
  if (items.length && items.every((i) => qcIsPass(i.result))) return 'ผ่าน'
  return 'กำลังตรวจ'
}
// สรุปความคืบหน้าต่องวดของบ้านหนึ่งหลัง: ฟอร์มที่ควรตรวจ / ตรวจแล้ว / ผ่านแล้ว
export function qcPhaseProgress(rows: { phase?: string; form_id?: string; status: string }[]) {
  return QC_PHASES.map((p) => {
    const forms = qcFormsOfPhase(p.id)
    const mine = rows.filter((r) => r.phase === p.id)
    const done = new Set(mine.filter((r) => r.status === 'ผ่าน').map((r) => r.form_id))
    const started = new Set(mine.map((r) => r.form_id))
    return { ...p, total: forms.length, started: started.size, passed: forms.filter((f) => done.has(f.id)).length, fixing: mine.filter((r) => r.status === 'ต้องแก้ไข').length }
  })
}
